"""Write the code page tables at the end of src/document/file_preview/codepage.rs.

Each table holds the characters for bytes 0x80 to 0xFF of one single-byte
code page, taken from Python's codecs. A byte the code page leaves
undefined becomes U+FFFD. Everything after the marker line in the Rust file
is replaced; the code above it is kept.

Usage: python3 tools/codepage_tables.py src/document/file_preview/codepage.rs
"""

import sys

CODE_PAGES = [437, 850, 874, 1250, 1251, 1252, 1253, 1254, 1255, 1256, 1257, 1258, 10000]
MARKER = "// Generated by tools/codepage_tables.py; do not edit below this line.\n"
PER_LINE = 9


def python_codec(code_page):
    """The name of Python's codec for a Windows or DOS code page number."""
    return "mac_roman" if code_page == 10000 else f"cp{code_page}"


def upper_half(code_page):
    """The 128 characters for bytes 0x80 to 0xFF, with U+FFFD for undefined bytes."""
    characters = []
    for byte in range(0x80, 0x100):
        try:
            characters.append(bytes([byte]).decode(python_codec(code_page)))
        except UnicodeDecodeError:
            characters.append("�")
    return characters


def rust_table(code_page):
    """One table as a Rust constant."""
    literals = [f"'\\u{{{ord(character):04X}}}'" for character in upper_half(code_page)]
    lines = [
        "    " + ", ".join(literals[start : start + PER_LINE]) + ","
        for start in range(0, len(literals), PER_LINE)
    ]
    body = "\n".join(lines)
    return f"/// Code page {code_page}.\nconst CP{code_page}: [char; 128] = [\n{body}\n];\n"


def main():
    path = sys.argv[1]
    with open(path, encoding="utf-8") as source:
        text = source.read()
    if MARKER not in text:
        sys.exit(f"{path} has no marker line: {MARKER.strip()}")
    kept = text[: text.index(MARKER) + len(MARKER)]
    tables = "\n".join(rust_table(code_page) for code_page in CODE_PAGES)
    with open(path, "w", encoding="utf-8") as target:
        target.write(kept + "\n" + tables)


if __name__ == "__main__":
    main()
